def _hex_to_rgb(hex_color):
    hex_color = hex_color.lstrip('#')
    return tuple(int(hex_color[i:i+2], 16) for i in (0, 2, 4))


def _contrast_text_color(bg_color):
    try:
        r, g, b = _hex_to_rgb(bg_color)
        luminance = (0.299 * r + 0.587 * g + 0.114 * b) / 255
        return '#1a1a2e' if luminance > 0.55 else '#ffffff'
    except Exception:
        return '#1a1a2e'


def build_color_preview_style(theme_name, color, text_color=None):
    theme = get_theme(theme_name)
    text = text_color or _contrast_text_color(color)
    control_border = theme.get("control_border", theme["border_strong"])
    return (
        "QPushButton {"
        f"background-color: {color};"
        f"color: {text};"
        f"border: 1px solid {control_border};"
        "border-radius: 4px;"
        "padding: 4px 8px;"
        "}"
    )
