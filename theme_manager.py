def list_theme_names():
    return list(THEMES.keys())


def get_theme(theme_name=None):
    return THEMES.get(theme_name, THEMES[DEFAULT_THEME_NAME])


def normalize_theme_name(theme_name):
    return theme_name if theme_name in THEMES else DEFAULT_THEME_NAME


def is_cartoon_theme(theme_name):
    return theme_name == "卡通乐园"


def get_theme_font(theme_name):
    if is_cartoon_theme(theme_name):
        return '"KaiTi", "STKaiti", "Microsoft YaHei", sans-serif'
    return '"Microsoft YaHei", "PingFang SC", "Noto Sans SC", sans-serif'


